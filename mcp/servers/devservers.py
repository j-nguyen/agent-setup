def tool_trust(args: dict) -> str:
    ctx = resolve(args.get("project_path"))
    given = args.get("hash")
    if not isinstance(given, str) or not given:
        raise ToolError("hash is required")
    cfg = load_config(ctx)
    if cfg is None:
        raise ToolError(f"no devservers config in {ctx.worktree}; nothing to trust")
    current = config_hash(cfg)
    if given != current:
        raise ToolError(f"stale hash: the config changed since it was shown (current hash {current}). Show the "
                        "user the current commands again (call start) before trusting.")
    trust_record(ctx, cfg)
    return f"Trusted config {current} for {ctx.root}."


def cli_trust(path: str) -> int:
    try:
        ctx = resolve(path)
        cfg = load_config(ctx)
    except ToolError as e:
        print(e, file=sys.stderr)
        return 1
    if cfg is None:
        print(f"no devservers config in {ctx.worktree}", file=sys.stderr)
        return 1
    print(f"Config of {ctx.worktree} (hash {config_hash(cfg)}) would run:")
    for c in commands_of(cfg):
        print(f"  {c}")
    if not (sys.stdin.isatty() and sys.stdout.isatty()):
        print("refusing to trust without a terminal to ask on", file=sys.stderr)
        return 1
    if input("Trust this config? [y/N] ").strip().lower() not in ("y", "yes"):
        print("not trusted")
        return 1
    trust_record(ctx, cfg)
    print("trusted")
    return 0


