def _install_for(wt: Path) -> tuple[str | None, str]:
    for lock, cmd in (("package-lock.json", "npm ci"), ("pnpm-lock.yaml", "pnpm install --frozen-lockfile"),
                      ("yarn.lock", "yarn install --frozen-lockfile"), ("bun.lock", "bun install --frozen-lockfile"),
                      ("bun.lockb", "bun install --frozen-lockfile"), ("Gemfile.lock", "bundle install"),
                      ("uv.lock", "uv sync"), ("poetry.lock", "poetry install"), ("mix.exs", "mix deps.get"),
                      ("composer.lock", "composer install"), ("go.mod", "go mod download"),
                      ("Cargo.toml", "cargo fetch")):
        if (wt / lock).is_file():
            return cmd, lock
    return None, ""


def _script_runner(wt: Path) -> str:
    if (wt / "yarn.lock").is_file():
        return "yarn"
    if (wt / "pnpm-lock.yaml").is_file():
        return "pnpm run"
    if (wt / "bun.lock").is_file() or (wt / "bun.lockb").is_file():
        return "bun run"
    return "npm run"


def build_proposal(ctx: Ctx) -> tuple[dict, list[str]]:
    wt, main = Path(ctx.worktree), Path(ctx.root)
    servers: dict[str, dict] = {}
    ports: dict[str, int] = {}
    detected: list[str] = []
    setup: dict = {}
    install, why = _install_for(wt)
    if install:
        setup["install"] = install
        detected.append(f"install `{install}` (found {why})")
    copy = [f for f in (".env",) if (main / f).is_file()]
    if copy:
        setup["copy"] = copy
        detected.append(f"copy {', '.join(copy)} from the main checkout")
    pkg = read_json(wt / "package.json", {}) or {}
    scripts = [s for s in (pkg.get("scripts") or {}) if isinstance(s, str) and s.startswith("dev")]
    for s in scripts:
        name = re.sub(r"[^a-z0-9]+", "-", s.lower()).strip("-") or "dev"
        servers[name] = {"run": f"{_script_runner(wt)} {s}"}
        detected.append(f"package.json script `{s}`")
    if (wt / "bin" / "dev").is_file():
        servers.setdefault("dev", {"run": "bin/dev"})
        detected.append("bin/dev")
    elif (wt / "Procfile.dev").is_file() or (wt / "Procfile").is_file():
        proc = "Procfile.dev" if (wt / "Procfile.dev").is_file() else "Procfile"
        servers.setdefault("dev", {"run": f"foreman start -f {proc}"})
        detected.append(proc)
    if (wt / "mix.exs").is_file():
        servers.setdefault("dev", {"run": "mix phx.server"})
        ports.setdefault("PORT", 4000)
        detected.append("mix.exs (Phoenix)")
    if (wt / "manage.py").is_file():
        servers.setdefault("dev", {"run": "python manage.py runserver 127.0.0.1:$PORT"})
        ports.setdefault("PORT", 8000)
        detected.append("manage.py (Django)")
    if (wt / "artisan").is_file():
        servers.setdefault("dev", {"run": "php artisan serve --port=$PORT"})
        ports.setdefault("PORT", 8000)
        detected.append("artisan (Laravel)")
    if (wt / "go.mod").is_file():
        servers.setdefault("dev", {"run": "go run ."})
        detected.append("go.mod")
    if (wt / "Cargo.toml").is_file():
        servers.setdefault("dev", {"run": "cargo run"})
        detected.append("Cargo.toml")
    for f in ("compose.yaml", "compose.yml", "docker-compose.yml", "docker-compose.yaml"):
        if (wt / f).is_file():
            servers.setdefault("compose", {"run": "docker compose up", "stop_signal": "INT"})
            detected.append(f)
            break
    cfg: dict = {}
    if setup:
        cfg["setup"] = setup
    if ports:
        cfg["ports"] = ports
    if servers:
        pick = "dev" if "dev" in servers else next(iter(servers))
        servers[pick]["default"] = True
        cfg["servers"] = servers
    return cfg, detected


def proposal_text(ctx: Ctx) -> str:
    cfg, detected = build_proposal(ctx)
    head = f"NOT STARTED: no devservers config in {ctx.worktree} (.agents/devservers.json or devservers.local.json)."
    if not cfg.get("servers"):
        return (head + " Nothing to propose was detected. Ask the user for the dev command and call "
                "`configure` with {\"servers\": {\"dev\": {\"run\": \"...\", \"default\": true}}} and a scope.")
    return (head + "\nProposal (nothing was executed; these are literal commands):\n"
            + json.dumps(cfg, indent=2) + "\nDetected: " + "; ".join(detected)
            + "\nShow this to the user. If they agree (they may edit it, add `ready.log`/`ports`), call `configure` "
            "with the config and scope `team` (committed, shared) or `local` (personal, git-excluded).")


