@dataclass
class Ctx:
    worktree: str      # this worktree's top-level directory
    root: str          # main checkout (project root)
    common: str | None  # git common dir, None outside git
    key: str
    pdir: Path

    @property
    def is_main(self) -> bool:
        return self.worktree == self.root


def resolve(project_path: str | None) -> Ctx:
    if project_path is not None and not isinstance(project_path, str):
        raise ToolError("project_path must be a string")
    raw = os.path.realpath(os.path.expanduser(project_path)) if project_path else os.path.realpath(os.getcwd())
    if not os.path.isdir(raw):
        raise ToolError(f"project_path is not a directory: {raw}")
    worktree, common = raw, None
    try:
        r = subprocess.run(["git", "-C", raw, "rev-parse", "--path-format=absolute", "--show-toplevel",
                            "--git-common-dir"], capture_output=True, text=True, timeout=10,
                           stdin=subprocess.DEVNULL)
        lines = r.stdout.splitlines()
        if r.returncode == 0 and len(lines) >= 2:
            worktree, common = os.path.realpath(lines[0]), os.path.realpath(lines[1])
    except (OSError, subprocess.SubprocessError):
        pass
    root = str(Path(common).parent) if common else worktree
    pdir = state_root() / slugify_path(root)
    return Ctx(worktree=worktree, root=root, common=common, key=slugify_path(root), pdir=pdir)


def wt_id(worktree: str) -> str:
    slug = slugify_path(worktree)[-60:]
    return f"{slug}-{hashlib.sha1(worktree.encode()).hexdigest()[:8]}"


def instance_path(ctx: Ctx, name: str) -> Path:
    return ctx.pdir / "instances" / f"{wt_id(ctx.worktree)}__{name}.json"


def log_path(ctx: Ctx, name: str) -> Path:
    return ctx.pdir / "logs" / f"{wt_id(ctx.worktree)}__{name}.log"


def marker_path(ctx: Ctx) -> Path:
    return ctx.pdir / "setup" / f"{wt_id(ctx.worktree)}.json"


# --------------------------------------------------------------------------- #
# Process identity and liveness
# --------------------------------------------------------------------------- #
_CHILDREN: dict[int, subprocess.Popen] = {}  # processes this server started: polled first so none stay zombies


def start_token(pid: int) -> str | None:
    """Stable start-time string of a process (`ps -o lstart=`), or None if it is gone."""
    try:
        r = subprocess.run(["ps", "-o", "lstart=", "-p", str(pid)], capture_output=True, text=True, timeout=5,
                           env={**os.environ, "LC_ALL": "C"}, stdin=subprocess.DEVNULL)
    except (OSError, subprocess.SubprocessError):
        return None
    out = r.stdout.strip()
    return out if r.returncode == 0 and out else None


def _states(args: list[str]) -> list[tuple[int, int, str]]:
    """(pid, pgid, state) rows from `ps`, or [] if ps fails."""
    try:
        r = subprocess.run(["ps", *args, "-o", "pid=,pgid=,stat="], capture_output=True, text=True, timeout=5,
                           env={**os.environ, "LC_ALL": "C"}, stdin=subprocess.DEVNULL)
    except (OSError, subprocess.SubprocessError):
        return []
    rows = []
    for line in r.stdout.splitlines():
        parts = line.split()
        if len(parts) >= 3 and parts[0].isdigit() and parts[1].isdigit():
            rows.append((int(parts[0]), int(parts[1]), parts[2]))
    return rows


# A process that another session's server started stays a zombie after it exits, because only its parent can
# reap it. Signal 0 still reaches a zombie, so a zombie is checked for and counted as stopped.
def is_zombie(pid: int) -> bool:
    return any(p == pid and stat.startswith("Z") for p, _, stat in _states(["-p", str(pid)]))


def group_has_live_member(pgid: int) -> bool:
    rows = _states(["-A"])
    return not rows or any(g == pgid and not stat.startswith("Z") for _, g, stat in rows)


def pid_alive(pid: int, token: str | None) -> bool:
    child = _CHILDREN.get(pid)
    if child is not None and child.poll() is not None:
        _CHILDREN.pop(pid, None)
        return False
    try:
        os.kill(pid, 0)
    except ProcessLookupError:
        return False
    except PermissionError:
        pass
    if is_zombie(pid):
        return False
    current = start_token(pid)
    return not (token and current and token != current)


def group_alive(rec: dict) -> bool:
    """Is the instance's process group alive? Own children are reaped first; a recycled leader pid is dead."""
    pid, pgid = rec["pid"], rec["pgid"]
    child = _CHILDREN.get(pid)
    if child is not None and child.poll() is not None:
        _CHILDREN.pop(pid, None)
    try:
        os.killpg(pgid, 0)
    except ProcessLookupError:
        return False
    except PermissionError:
        # macOS refuses a signal to a group that holds only zombies.
        return group_has_live_member(pgid)
    if not group_has_live_member(pgid):
        return False
    current = start_token(pid)
    if current is not None and rec.get("token") and current != rec["token"]:
        return False  # the leader's pid now belongs to another process
    return True


def signal_group(rec: dict, sig: int) -> None:
    try:
        os.killpg(rec["pgid"], sig)
    except (ProcessLookupError, PermissionError):
        pass


# --------------------------------------------------------------------------- #
# Per-project lock: a mkdir lock with an owner file, held only for read-modify-write
# --------------------------------------------------------------------------- #
def _lock_stale(lock: Path) -> bool:
    try:
        owner = (lock / "owner").read_text(encoding="utf-8").split()
    except OSError:
        try:  # owner not written yet: only stale if the directory has been there a while
            return now() - lock.stat().st_mtime > OWNERLESS_LOCK_STALE
        except OSError:
            return False
    try:
        pid = int(owner[0])
    except (IndexError, ValueError):
        return True
    token = owner[1] if len(owner) > 1 and owner[1] != "-" else None
    return not pid_alive(pid, token)


def _break_lock(lock: Path) -> None:
    stale = lock.with_name(f"{lock.name}.stale-{os.getpid()}-{int(now() * 1000)}")
    try:
        os.rename(lock, stale)  # atomic: only one taker wins
    except OSError:
        return
    shutil.rmtree(stale, ignore_errors=True)


_OWN_TOKEN: str | None = None


def _own_token() -> str:
    # `ps` can take seconds on a busy machine. Run it once, so the lock directory never waits for it
    # without an owner file and looks stale to another caller.
    global _OWN_TOKEN
    if _OWN_TOKEN is None:
        _OWN_TOKEN = start_token(os.getpid()) or "-"
    return _OWN_TOKEN


@contextmanager
def project_lock(pdir: Path):
    _own_token()
    ensure_dir(pdir)
    lock = pdir / "lock"
    deadline = time.monotonic() + LOCK_WAIT
    while True:
        try:
            lock.mkdir(mode=0o700)
            break
        except FileExistsError:
            pass
        if _lock_stale(lock):
            _break_lock(lock)
            continue
        if time.monotonic() > deadline:
            raise ToolError(f"could not get the project lock within {int(LOCK_WAIT)} s ({lock})")
        time.sleep(0.05)
    try:
        (lock / "owner").write_text(f"{os.getpid()} {_own_token()}\n", encoding="utf-8")
        yield
    finally:
        shutil.rmtree(lock, ignore_errors=True)


