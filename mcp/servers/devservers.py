def trust_file(ctx: Ctx) -> Path:
    return ctx.pdir / "trust.json"


def trust_record(ctx: Ctx, cfg: dict) -> str:
    h = config_hash(cfg)
    store = read_json(trust_file(ctx), {}) or {}
    store.setdefault("trusted", {})[h] = {"config": cfg, "time": iso()}
    store["last"] = h
    write_json(trust_file(ctx), store)
    return h


def is_trusted(ctx: Ctx, cfg: dict) -> bool:
    store = read_json(trust_file(ctx), {}) or {}
    return config_hash(cfg) in (store.get("trusted") or {})


def commands_of(cfg: dict) -> list[str]:
    out = []
    setup = cfg.get("setup")
    if isinstance(setup, str):
        out.append(f"setup: {setup}")
    elif isinstance(setup, dict):
        out += [f"setup.{k}: {setup[k]}" for k in ("install", "after_install") if k in setup]
        if setup.get("copy"):
            out.append(f"setup.copy (from the main checkout): {', '.join(setup['copy'])}")
    for i, p in enumerate(cfg.get("preflight", [])):
        out.append(f"preflight[{i}] ({p.get('in', 'worktree')}): {p['run']}")
    for name, s in cfg.get("servers", {}).items():
        out.append(f"servers.{name}: {s['run']}")
    return out


def untrusted_error(ctx: Ctx, cfg: dict) -> ToolError:
    store = read_json(trust_file(ctx), {}) or {}
    last = (store.get("trusted") or {}).get(store.get("last", ""), {}).get("config")
    h = config_hash(cfg)
    lines = [f"NOT RUN: the devservers config of {ctx.worktree} is not trusted (hash {h}).",
             "Commands it would run:"] + [f"  {c}" for c in commands_of(cfg)]
    if last is not None:
        diff = list(difflib.unified_diff(json.dumps(last, indent=2, sort_keys=True).splitlines(),
                                         json.dumps(cfg, indent=2, sort_keys=True).splitlines(),
                                         "trusted", "current", lineterm="", n=2))
        lines += ["Changes since the trusted config:"] + [f"  {d}" for d in diff]
    lines.append("Ask the user to review these commands. Only after they approve, call `trust` with this hash "
                 f"(or they can run: python3 {Path(__file__).resolve()} trust {ctx.worktree}).")
    return ToolError("\n".join(lines))


def need_trusted(ctx: Ctx) -> dict:
    """Load the config; no config -> proposal error; untrusted -> trust request. Returns the config."""
    cfg = load_config(ctx)
    if cfg is None:
        raise ToolError(proposal_text(ctx))
    if not is_trusted(ctx, cfg):
        raise untrusted_error(ctx, cfg)
    return cfg


