def pick_server(cfg: dict, name) -> tuple[str, dict]:
    servers = cfg["servers"]
    if name is None:
        defaults = [n for n, s in servers.items() if s.get("default")]
        if defaults:
            name = defaults[0]
        elif len(servers) == 1:
            name = next(iter(servers))
        else:
            raise ToolError(f"name is required; servers: {', '.join(sorted(servers))}")
    if not isinstance(name, str) or name not in servers:
        raise ToolError(f"unknown server {name!r}; servers: {', '.join(sorted(servers))}")
    return name, servers[name]


def run_preflight(ctx: Ctx, cfg: dict, env: dict[str, str]) -> None:
    for item in cfg.get("preflight") or []:
        cwd = ctx.root if item.get("in") == "main" else ctx.worktree
        try:
            r = subprocess.run(["/bin/sh", "-c", item["run"]], cwd=cwd, env=env, capture_output=True, text=True,
                               timeout=PREFLIGHT_TIMEOUT, stdin=subprocess.DEVNULL)
            failed, tail = r.returncode != 0, (r.stdout + r.stderr).strip()[-600:]
        except subprocess.TimeoutExpired:
            failed, tail = True, f"timed out after {PREFLIGHT_TIMEOUT} s"
        if failed:
            hint = item.get("hint")
            raise ToolError(f"NOT STARTED: preflight failed: {item['run']} (in {item.get('in', 'worktree')})"
                            + (f"\nHint: {hint}" if hint else "") + (f"\n{tail}" if tail else ""))


def start_instance(ctx: Ctx, cfg: dict, name: str) -> tuple[dict, bool]:
    """Steps 2-3 of the start flow for a trusted config. Returns (record, already_running)."""
    server = cfg["servers"][name]
    reason = setup_problem(ctx, cfg)
    if reason:
        raise setup_refusal(ctx, reason)
    if cfg.get("preflight"):
        with locked(ctx):
            slot = slot_for(ctx)
        run_preflight(ctx, cfg, build_env(ctx, cfg, slot, port_map(cfg, slot)))
    with locked(ctx, touch=name):
        rec = load_record(ctx, name)
        if rec and rec["state"] == "running":
            return rec, True
        limit = cfg.get("max_running")
        if limit is not None:
            live = [(read_json(f) or {}) for f in (ctx.pdir / "instances").glob("*.json")]
            live = [r for r in live if r.get("state") == "running" and r.get("kind") == "server"]
            if len(live) >= limit:
                names = ", ".join(f"{r['name']} in {r['worktree']}" for r in live)
                raise ToolError(f"NOT STARTED: max_running is {limit} and {len(live)} server(s) run: {names}. "
                                "Stop one first.")
        slot = slot_for(ctx)
        injected = port_map(cfg, slot)
        ports = {**file_ports(ctx, cfg), **injected}
        if "port_keys" in server:
            missing = sorted(set(server["port_keys"]) - ports.keys())
            if missing:
                raise ToolError(f"NOT STARTED: missing port values for {', '.join(missing)} in {ctx.worktree}")
            ports = {key: ports[key] for key in server["port_keys"]}
        for key, port in sorted(ports.items()):
            if not port_free(port):
                raise ToolError(f"NOT STARTED: port {port} ({key}) is already in use by {port_holder(ctx, port)}")
        sig, timeout = server_stop_settings(cfg, server)
        rec = spawn(ctx, name, "server", server["run"], build_env(ctx, cfg, slot, injected), slot=slot, ports=ports,
                    ready=server.get("ready") or {}, stop_signal=sig, stop_timeout=timeout,
                    idle_minutes=cfg.get("idle_timeout_minutes", 0))
        save_record(rec, ctx)
        return rec, False


def tool_start(args: dict) -> str:
    auto_setup = args.get("setup_if_needed", False)
    if not isinstance(auto_setup, bool):
        raise ToolError("setup_if_needed must be a boolean")
    timeout = _int_arg(args, "setup_timeout_sec", DEFAULT_SETUP_WAIT, 1, MAX_WAIT)
    ctx = resolve(args.get("project_path"))
    cfg = need_trusted(ctx)
    name, _ = pick_server(cfg, args.get("name"))
    if auto_setup and setup_problem(ctx, cfg):
        setup = queue_setup(ctx, cfg, only_if_needed=True)
        if setup.get("run_id"):
            out = wait_for_instance(ctx, "setup", timeout)
            if out["result"] != "ready":
                out["phase"] = "setup"
                out["next"] = "Retry start with setup_if_needed=true." if out["result"] == "waiting" else "Inspect setup logs."
                return js(out)
        if config_hash(need_trusted(ctx)) != config_hash(cfg):
            raise ToolError("the config changed during setup; call start again")
    rec, existing = start_instance(ctx, cfg, name)
    note = "already running" if existing else "started"
    return js({"result": note, **describe(ctx, rec, check=False),
               "next": f"wait_ready(name={name!r}) then logs/status"})


def stop_instance(ctx: Ctx, name: str) -> dict:
    with locked(ctx, touch=name):
        rec = load_record(ctx, name)
        if rec is None:
            raise ToolError(f"no instance named {name!r} in {ctx.worktree}")
        if rec["state"] != "running":
            return {"result": "already stopped", **describe(ctx, rec, check=False)}
        sig_name = rec.get("stop_signal", "TERM")
        timeout = rec.get("stop_timeout", DEFAULT_STOP_TIMEOUT)
        rec["stopping"] = {"signal": sig_name, "reason": "stop", "kill_at": now() + timeout}
        save_record(rec, ctx)
        signal_group(rec, STOP_SIGNALS.get(sig_name, signal.SIGTERM))
    deadline = time.monotonic() + timeout
    while group_alive(rec) and time.monotonic() < deadline:
        time.sleep(0.05)
    killed = False
    if group_alive(rec):
        killed = True
        with project_lock(ctx.pdir):  # note the KILL in the record before the reap finalises it
            cur = load_record(ctx, name)
            if cur and cur.get("run_id") == rec["run_id"] and cur.get("stopping"):
                cur["stopping"]["killed"] = True
                save_record(cur, ctx)
        signal_group(rec, signal.SIGKILL)
        end = time.monotonic() + 5
        while group_alive(rec) and time.monotonic() < end:
            time.sleep(0.05)
    with locked(ctx):  # the reap records the exit
        final = load_record(ctx, name) or rec
    msg = (f"did not exit within {timeout} s after {sig_name}; sent KILL" if killed
           else f"stopped with {sig_name}")
    return {"result": msg, **describe(ctx, final, check=False)}


