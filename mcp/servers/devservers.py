def _safe_dest(base: Path, rel: str) -> Path | None:
    dest = base / rel
    real_parent = Path(os.path.realpath(dest.parent))
    real_base = Path(os.path.realpath(base))
    return dest if real_parent == real_base or real_base in real_parent.parents else None


def copy_ignored(ctx: Ctx, items: list[str]) -> list[str]:
    """Copy from the main checkout when absent in the worktree. Relative paths only; never overwrites."""
    notes = []
    main, wt = Path(ctx.root), Path(ctx.worktree)
    for rel in items:
        if _bad_relpath(rel):
            notes.append(f"skip {rel}: not a safe relative path")
            continue
        if ctx.is_main:
            notes.append(f"skip {rel}: this is the main checkout")
            continue
        src, dest = main / rel, _safe_dest(wt, rel)
        real_main = Path(os.path.realpath(main))
        if dest is None or not (src.exists() or src.is_symlink()):
            notes.append(f"skip {rel}: {'not inside the worktree' if dest is None else 'not in the main checkout'}")
            continue
        if real_main not in Path(os.path.realpath(src)).parents:
            notes.append(f"skip {rel}: resolves outside the main checkout")
            continue
        if os.path.lexists(dest):
            notes.append(f"skip {rel}: already exists")
            continue
        dest.parent.mkdir(parents=True, exist_ok=True)
        if src.is_dir():
            shutil.copytree(src, dest, symlinks=True)
        else:
            shutil.copy2(src, dest)
        notes.append(f"copied {rel}")
    return notes


def write_env_file(ctx: Ctx, slot: int, ports: dict[str, int]) -> str:
    dest = Path(ctx.worktree) / ENV_FILE
    if dest.exists() and not dest.read_text(encoding="utf-8", errors="replace").startswith(ENV_FILE_HEADER):
        return f"skip {ENV_FILE}: exists and is not ours"
    lines = [ENV_FILE_HEADER, f"DEVSERVERS_SLOT={slot}"]
    lines += [f"{k}={v}" for k, v in sorted(ports.items())]
    if slot >= 1:
        lines.append(f"COMPOSE_PROJECT_NAME={compose_name(ctx, slot)}")
    dest.write_text("\n".join(lines) + "\n", encoding="utf-8")
    add_exclude(ctx, ENV_FILE)
    return f"wrote {ENV_FILE}"


def queue_setup(ctx: Ctx, cfg: dict, *, only_if_needed: bool = False) -> dict:
    setup = cfg["setup"]
    notes: list[str] = []
    with locked(ctx, touch="setup"):
        rec = load_record(ctx, "setup")
        if rec and rec["state"] == "running":
            return {"result": "setup already running", **describe(ctx, rec, check=False),
                    "next": "wait_ready(task=\"setup\")"}
        if only_if_needed and setup_problem(ctx, cfg) is None:
            return {"result": "setup already complete"}
        slot = slot_for(ctx)
        ports = port_map(cfg, slot)
        info ={"wt_id": wt_id(ctx.worktree), "lock_digest": "", "config_hash": config_hash(cfg)}
        marker_path(ctx).unlink(missing_ok=True)
        if isinstance(setup, str):
            command = setup
        else:
            notes += copy_ignored(ctx, setup.get("copy") or [])
            notes.append(write_env_file(ctx, slot, ports))
            steps = [setup[k] for k in ("install", "after_install") if k in setup]
            command = " && ".join(f"( {s} )" for s in steps)
        if not command:
            info["lock_digest"] = lock_digest(Path(ctx.worktree))
            write_json(marker_path(ctx), {"lock_digest": info["lock_digest"], "config_hash": info["config_hash"],
                                          "time": iso()})
            return {"result": "setup complete (nothing to run)", "slot": slot, "notes": notes}
        info["lock_digest"] = lock_digest(Path(ctx.worktree))
        env = build_env(ctx, cfg, slot, ports)
        rec = spawn(ctx, "setup", "task", command, env, slot=slot, ports=ports, on_success=info)
        save_record(rec, ctx)
    return {"result": "setup started", "notes": notes, **describe(ctx, rec, check=False),
            "next": "wait_ready(task=\"setup\"), then start"}


