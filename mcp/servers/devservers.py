def add_exclude(ctx: Ctx, pattern: str) -> None:
    if not ctx.common:
        return
    path = Path(ctx.common) / "info" / "exclude"
    try:
        text = path.read_text(encoding="utf-8") if path.exists() else ""
    except OSError:
        return
    if pattern in text.splitlines():
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text + ("" if not text or text.endswith("\n") else "\n") + pattern + "\n", encoding="utf-8")


def tool_configure(args: dict) -> str:
    ctx = resolve(args.get("project_path"))
    scope = args.get("scope")
    if scope not in ("team", "local"):
        raise ToolError("scope must be `team` or `local`")
    config = check_schema(args.get("config"), f"{scope} (new)")
    agents = Path(ctx.worktree) / ".agents"
    other = _read_config_file(agents / (LOCAL_FILE if scope == "team" else TEAM_FILE),
                              "local" if scope == "team" else "team")
    new_merged = merge_config(config, other) if scope == "team" else merge_config(other, config)
    check_merged(new_merged)
    target = agents / (TEAM_FILE if scope == "team" else LOCAL_FILE)
    write_atomic(target, json.dumps(config, indent=2) + "\n", mode=0o644 if scope == "team" else 0o600)
    if scope == "local":
        add_exclude(ctx, f".agents/{LOCAL_FILE}")
    h = trust_record(ctx, new_merged)  # the user just confirmed this exact content
    return f"Wrote {target} and trusted it (hash {h}). Next: `setup` if the config has one, then `start`."


