def spawn(ctx: Ctx, name: str, kind: str, command: str, env: dict[str, str], **extra) -> dict:
    """Start `command` detached in its own session; one merged log; the exit code ends up in the log (D1)."""
    lp = log_path(ctx, name)
    ensure_dir(lp.parent)
    if lp.exists():
        os.replace(lp, lp.with_name(lp.name + ".1"))
    run_id = f"{int(now() * 1000):x}"
    fd = os.open(lp, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    # The inner `sh -c` keeps the marker even when the command ends in `exec`.
    script = f'/bin/sh -c "$1"; echo "{EXIT_MARKER} $?"'
    try:
        proc = subprocess.Popen(["/bin/sh", "-c", script, "devservers", command], cwd=ctx.worktree, env=env,
                                stdin=subprocess.DEVNULL, stdout=fd, stderr=subprocess.STDOUT,
                                start_new_session=True)
    except OSError as e:
        raise ToolError(f"could not start {name}: {e}") from e
    finally:
        os.close(fd)
    _CHILDREN[proc.pid] = proc
    t = now()
    return {"name": name, "kind": kind, "state": "running", "worktree": ctx.worktree, "command": command,
            "pid": proc.pid, "pgid": proc.pid, "token": start_token(proc.pid), "run_id": run_id,
            "log": str(lp), "started": t, "last_touch": t, **extra}


def exit_code_from_log(path: str) -> int | None:
    try:
        with open(path, "rb") as f:
            f.seek(0, os.SEEK_END)
            f.seek(max(0, f.tell() - 4096))
            tail = f.read().decode("utf-8", errors="replace")
    except OSError:
        return None
    found = EXIT_RE.findall(tail)
    return int(found[-1]) if found else None


def write_marker(rec: dict, pdir: Path) -> None:
    info = rec.get("on_success")
    if info:
        write_json(pdir / "setup" / f"{info['wt_id']}.json",
                   {"lock_digest": info["lock_digest"], "config_hash": info["config_hash"], "time": iso()})


def finish_record(rec: dict, pdir: Path) -> None:
    code = exit_code_from_log(rec["log"])
    rec["state"] = "exited"
    rec["last_exit"] = {"code": code, "time": iso(), "log": rec["log"],
                        "stopped": bool(rec.get("stopping")), "killed": bool((rec.get("stopping") or {}).get("killed"))}
    if rec.get("kind") == "task" and code == 0:
        write_marker(rec, pdir)


def reap_dir(pdir: Path) -> None:
    """Refresh every record of one project. Call under the project lock."""
    slots = read_json(pdir / "slots.json", {}) or {}
    for f in sorted((pdir / "instances").glob("*.json")):
        rec = read_json(f)
        if not isinstance(rec, dict) or "worktree" not in rec:
            f.unlink(missing_ok=True)
            continue
        if not os.path.isdir(rec["worktree"]):
            f.unlink(missing_ok=True)
            continue
        if rec.get("state") != "running":
            continue
        t = now()
        if not group_alive(rec):
            finish_record(rec, pdir)
            write_json(f, rec)
            continue
        stopping = rec.get("stopping")
        if stopping is None and rec.get("kind") == "server" and rec.get("idle_minutes"):
            if t - rec.get("last_touch", t) > rec["idle_minutes"] * 60:
                signal_group(rec, signal.SIGTERM)
                rec["stopping"] = {"signal": "TERM", "reason": "idle",
                                   "kill_at": t + rec.get("stop_timeout", DEFAULT_STOP_TIMEOUT)}
                write_json(f, rec)
        elif stopping and t > stopping.get("kill_at", t) and not stopping.get("killed"):
            signal_group(rec, signal.SIGKILL)
            stopping["killed"] = True
            write_json(f, rec)
    gone = [wt for wt in slots if not os.path.isdir(wt)]
    if gone:
        for wt in gone:
            del slots[wt]
        write_json(pdir / "slots.json", slots)


@contextmanager
def locked(ctx: Ctx, touch: str | None = None):
    """Take the project lock, reap, optionally mark the worktree's instance(s) as used; yield."""
    with project_lock(ctx.pdir):
        write_json(ctx.pdir / "project.json", {"root": ctx.root})
        if touch is not None:  # before the reap, so this very call keeps its instance from idling out
            for f in (ctx.pdir / "instances").glob(f"{wt_id(ctx.worktree)}__*.json"):
                rec = read_json(f)
                if isinstance(rec, dict) and rec.get("state") == "running":
                    rec["last_touch"] = now()
                    write_json(f, rec)
        reap_dir(ctx.pdir)
        yield


def refreshed(ctx: Ctx, name: str) -> dict | None:
    """The instance record after a reap (takes the lock briefly)."""
    with locked(ctx):
        return load_record(ctx, name)


