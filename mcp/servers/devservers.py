def lock_digest(wt: Path) -> str:
    h = hashlib.sha256()
    for name in LOCKFILES:
        p = wt / name
        if p.is_file():
            h.update(name.encode() + b"\0" + hashlib.sha256(p.read_bytes()).digest())
    return h.hexdigest()


def setup_problem(ctx: Ctx, cfg: dict) -> str | None:
    """Why this worktree needs `setup`, or None when it is ready (or the config has no setup)."""
    if "setup" not in cfg:
        return None
    marker = read_json(marker_path(ctx))
    if not marker:
        return "this worktree has not been set up"
    if marker.get("config_hash") != config_hash(cfg):
        return "the config changed since the last setup"
    if marker.get("lock_digest") != lock_digest(Path(ctx.worktree)):
        return "a lockfile changed since the last setup"
    return None


def setup_refusal(ctx: Ctx, reason: str) -> ToolError:
    return ToolError(f"NOT STARTED: {reason}. Next: setup(project_path={ctx.worktree!r}), then "
                     f"wait_ready(project_path={ctx.worktree!r}, task=\"setup\"), then start.")


