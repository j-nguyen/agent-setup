# --------------------------------------------------------------------------- #
# JSON-RPC 2.0 over newline-delimited stdio
# --------------------------------------------------------------------------- #
def _error(rid, code: int, message: str) -> dict:
    return {"jsonrpc": "2.0", "id": rid, "error": {"code": code, "message": message}}


def _result(rid, result: dict) -> dict:
    return {"jsonrpc": "2.0", "id": rid, "result": result}


def handle_message(msg) -> dict | None:
    """Return the response for one decoded message, or None when no reply is due."""
    if not isinstance(msg, dict) or not isinstance(msg.get("method"), str):
        return _error(msg.get("id") if isinstance(msg, dict) else None, -32600, "invalid request")
    method, rid = msg["method"], msg.get("id")
    if "id" not in msg:  # notification: never answered
        return None
    params = msg.get("params")
    params = params if isinstance(params, dict) else {}
    if method == "initialize":
        asked = params.get("protocolVersion")
        version = asked if asked in PROTOCOL_VERSIONS else PROTOCOL_VERSIONS[0]
        return _result(rid, {"protocolVersion": version, "capabilities": {"tools": {}},
                             "serverInfo": SERVER_INFO, "instructions": INSTRUCTIONS})
    if method == "ping":
        return _result(rid, {})
    if method == "tools/list":
        return _result(rid, {"tools": TOOLS})
    if method == "tools/call":
        func = TOOL_FUNCS.get(params.get("name"))
        if func is None:
            return _error(rid, -32602, f"unknown tool: {params.get('name')!r}")
        arguments = params.get("arguments")
        try:
            if arguments is not None and not isinstance(arguments, dict):
                raise ToolError("arguments must be an object")
            text, is_error = func(arguments or {}), False
        except ToolError as e:
            text, is_error = str(e), True
        except OSError as e:
            text, is_error = f"storage error: {e}", True
        return _result(rid, {"content": [{"type": "text", "text": text}], "isError": is_error})
    return _error(rid, -32601, f"method not found: {method}")


def serve(stdin=None, stdout=None) -> int:
    stdin, stdout = stdin or sys.stdin, stdout or sys.stdout
    for line in stdin:
        line = line.strip()
        if not line:
            continue
        try:
            msg = json.loads(line)
        except json.JSONDecodeError:
            resp = _error(None, -32700, "parse error")
        else:
            try:
                resp = handle_message(msg)
            except Exception as e:  # keep the loop alive; report on stderr
                warn(f"internal error: {e!r}")
                resp = _error(msg.get("id") if isinstance(msg, dict) else None, -32603, "internal error")
        if resp is not None:
            stdout.write(json.dumps(resp) + "\n")
            stdout.flush()
    return 0


OPEN_FILES_TARGET = 65536


def raise_open_file_limit(target: int = OPEN_FILES_TARGET) -> None:
    """Raise the soft open-file limit, which every server we start inherits.

    An app that macOS launchd starts gets a soft limit of 256. A file watcher such as Next.js needs thousands, so
    it fails with "EMFILE: too many open files, watch". A shell usually has a much higher limit, so this makes a
    server started here behave like one started from a terminal. It never lowers the limit, and it stays under
    the hard limit.
    """
    try:
        import resource
    except ImportError:  # not a Unix system
        return
    soft, hard = resource.getrlimit(resource.RLIMIT_NOFILE)
    wanted = target if hard == resource.RLIM_INFINITY else min(target, hard)
    if soft == resource.RLIM_INFINITY or soft >= wanted:
        return
    try:
        resource.setrlimit(resource.RLIMIT_NOFILE, (wanted, hard))
    except (ValueError, OSError):
        pass  # the system refused. Servers keep the old limit.


def main(argv: list[str]) -> int:
    raise_open_file_limit()
    if argv and argv[0] == "trust" and len(argv) == 2:
        return cli_trust(argv[1])
    if argv:
        print("usage: devservers.py [trust <path>]", file=sys.stderr)
        return 2
    return serve()


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
