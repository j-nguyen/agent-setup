def strip_ansi(s: str) -> str:
    """Remove ANSI escapes; for carriage-return redraws keep the last non-empty segment."""
    s = ANSI_RE.sub("", s)
    if "\r" not in s:
        return s
    return next((p for p in reversed(s.split("\r")) if p), "")


def read_log_text(path: str, limit: int = 8 * 1024 * 1024) -> str:
    try:
        with open(path, "rb") as f:
            f.seek(0, os.SEEK_END)
            f.seek(max(0, f.tell() - limit))
            return f.read().decode("utf-8", errors="replace")
    except OSError:
        return ""


def ready_port(port: int | str, rec: dict) -> int | None:
    value = port if isinstance(port, int) else (
        (rec.get("ports") or {}).get(port) or (rec.get("captured") or {}).get(port))
    return value if _is_int(value) and 0 < value < 65536 else None


def _probe_timeouts():
    """Per-host timeouts for one probe; stops when PROBE_BUDGET is spent."""
    deadline = time.monotonic() + PROBE_BUDGET
    for host in LOOPBACK:
        left = deadline - time.monotonic()
        if left <= 0:
            return
        yield host, min(PROBE_HOST_TIMEOUT, left)


def tcp_ready(port: int | None) -> bool:
    if port is None:
        return False
    for host, timeout in _probe_timeouts():
        try:
            with socket.create_connection((host, port), timeout=timeout):
                return True
        except OSError:
            pass
    return False


def http_ready(port: int | None, path: str) -> bool:
    if port is None:
        return False
    for host, timeout in _probe_timeouts():
        conn = HTTPConnection(host, port, timeout=timeout)
        try:
            conn.request("GET", path)
            with conn.getresponse() as reply:
                if 200 <= reply.status < 400:
                    return True
        except (OSError, HTTPException):
            pass
        finally:
            conn.close()
    return False


def check_ready(ctx: Ctx, rec: dict) -> bool:
    """Evaluate the record's ready conditions (all that are set); records captured ports."""
    ready = rec.get("ready") or {}
    if rec.get("state") != "running":
        return False
    ok = True
    captured = dict(rec.get("captured") or {})
    if ready.get("log"):
        rx = re.compile(ready["log"])
        hit = False
        for line in read_log_text(rec["log"]).splitlines():
            m = rx.search(strip_ansi(line))
            if m:
                hit = True
                captured.update({k: int(v) for k, v in m.groupdict().items() if v and v.isdigit()})
                break
        ok = ok and hit
    if captured != (rec.get("captured") or {}):
        with locked(ctx):
            cur = load_record(ctx, rec["name"])
            if cur and cur.get("run_id") == rec.get("run_id"):
                cur["captured"] = captured
                save_record(cur, ctx)
        rec["captured"] = captured
    if ready.get("port") is not None:
        ok = ok and tcp_ready(ready_port(ready["port"], rec))
    return ok and all(http_ready(ready_port(probe["port"], rec), probe["path"])
                      for probe in ready.get("http", []))


def describe(ctx: Ctx, rec: dict, check: bool = True) -> dict:
    out = {"name": rec["name"], "kind": rec["kind"], "state": rec["state"], "pid": rec["pid"],
           "worktree": rec["worktree"], "log": rec["log"], "run_id": rec["run_id"],
           "started": iso(rec["started"]), "command": rec["command"]}
    if rec.get("slot") is not None:
        out["slot"] = rec["slot"]
    ports = {**(rec.get("ports") or {}), **(rec.get("captured") or {})}
    if ports:
        out["ports"] = ports
    if rec["state"] == "running":
        out["uptime_sec"] = int(now() - rec["started"])
        if rec["kind"] == "server" and check:
            out["ready"] = check_ready(ctx, rec)
        if rec.get("stopping"):
            out["stopping"] = rec["stopping"]["reason"]
    else:
        out["last_exit"] = rec.get("last_exit")
    return out


