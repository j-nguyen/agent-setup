TOP_KEYS = {"setup", "preflight", "ports", "ports_from", "env", "env_strip", "max_running",
            "idle_timeout_minutes", "servers", "inherit_worktrees"}
SETUP_KEYS = {"copy", "install", "after_install"}
PREFLIGHT_KEYS = {"run", "in", "hint"}
SERVER_KEYS = {"run", "default", "stop_signal", "stop_timeout", "ready", "port_keys"}
READY_KEYS = {"log", "port", "http", "timeout_sec"}


def _is_int(v) -> bool:
    return isinstance(v, int) and not isinstance(v, bool)


def _is_str_list(v) -> bool:
    return isinstance(v, list) and all(isinstance(x, str) for x in v)


def _unknown(obj: dict, allowed: set, where: str, errs: list) -> None:
    for k in sorted(set(obj) - allowed):
        errs.append(f"{where}: unknown key {k!r}")


def _check_setup(v, errs: list) -> None:
    if isinstance(v, str):
        if not v.strip():
            errs.append("setup: command must not be empty")
        return
    if not isinstance(v, dict):
        errs.append("setup: must be a command string or an object {copy, install, after_install}")
        return
    _unknown(v, SETUP_KEYS, "setup", errs)
    if "copy" in v and not _is_str_list(v["copy"]):
        errs.append("setup.copy: must be a list of relative paths")
    for k in ("install", "after_install"):
        if k in v and (not isinstance(v[k], str) or not v[k].strip()):
            errs.append(f"setup.{k}: must be a non-empty command string")


def _valid_port_ref(port) -> bool:
    return (_is_int(port) and 0 < port < 65536
            or isinstance(port, str) and ENV_KEY_RE.fullmatch(port) is not None)


def _check_ready(v, where: str, errs: list) -> None:
    if not isinstance(v, dict):
        errs.append(f"{where}: must be an object")
        return
    _unknown(v, READY_KEYS, where, errs)
    if "log" in v:
        if not isinstance(v["log"], str):
            errs.append(f"{where}.log: must be a regex string")
        else:
            try:
                rx = re.compile(v["log"])
                for g in rx.groupindex:
                    if not ENV_KEY_RE.match(g):
                        errs.append(f"{where}.log: group name {g!r} is not an env var name")
            except re.error as e:
                errs.append(f"{where}.log: invalid regex: {e}")
    if "port" in v and not _valid_port_ref(v["port"]):
        errs.append(f"{where}.port: must be a port number or the name of a port (a `ports` key)")
    if "http" in v:
        probes = v["http"]
        if not isinstance(probes, list) or not probes:
            errs.append(f"{where}.http: must be a non-empty list of HTTP checks")
        else:
            for i, probe in enumerate(probes):
                label = f"{where}.http[{i}]"
                if not isinstance(probe, dict):
                    errs.append(f"{label}: must be an object")
                    continue
                _unknown(probe, {"port", "path"}, label, errs)
                if not _valid_port_ref(probe.get("port")):
                    errs.append(f"{label}.port: must be a port number or the name of a port")
                path = probe.get("path")
                if not isinstance(path, str) or not re.fullmatch(r"/[!-~]*", path) or path.startswith("//"):
                    errs.append(f"{label}.path: must be a local HTTP path, such as /health")
    if "timeout_sec" in v and not (_is_int(v["timeout_sec"]) and v["timeout_sec"] > 0):
        errs.append(f"{where}.timeout_sec: must be a positive integer")


def _check_server(name, s, errs: list) -> None:
    where = f"servers.{name}"
    if not isinstance(name, str) or len(name) > MAX_NAME or not NAME_RE.match(name):
        errs.append(f"{where}: server names are lowercase letters, digits and single hyphens, at most 64 chars")
    elif name == "setup":
        errs.append(f"{where}: `setup` is reserved for the setup task")
    if not isinstance(s, dict):
        errs.append(f"{where}: must be an object")
        return
    _unknown(s, SERVER_KEYS, where, errs)
    if not isinstance(s.get("run"), str) or not s["run"].strip():
        errs.append(f"{where}.run: required, a non-empty command string")
    if "default" in s and not isinstance(s["default"], bool):
        errs.append(f"{where}.default: must be true or false")
    if "stop_signal" in s and s["stop_signal"] not in STOP_SIGNALS:
        errs.append(f"{where}.stop_signal: one of {', '.join(STOP_SIGNALS)}")
    if "stop_timeout" in s and not (_is_int(s["stop_timeout"]) and s["stop_timeout"] > 0):
        errs.append(f"{where}.stop_timeout: must be a positive integer (seconds)")
    if "ready" in s:
        _check_ready(s["ready"], f"{where}.ready", errs)
    if "port_keys" in s and not (_is_str_list(s["port_keys"])
                                 and all(ENV_KEY_RE.fullmatch(k) for k in s["port_keys"])):
        errs.append(f"{where}.port_keys: must be a list of env var names")


def check_schema(cfg, label: str) -> dict:
    """Strict per-file schema check. Returns cfg or raises ToolError listing every problem."""
    errs: list[str] = []
    if not isinstance(cfg, dict):
        raise ToolError(f"invalid config ({label}): top level must be an object")
    _unknown(cfg, TOP_KEYS, "config", errs)
    if "setup" in cfg:
        _check_setup(cfg["setup"], errs)
    if "inherit_worktrees" in cfg and not isinstance(cfg["inherit_worktrees"], bool):
        errs.append("inherit_worktrees: must be true or false")
    if "preflight" in cfg:
        pf = cfg["preflight"]
        if not isinstance(pf, list):
            errs.append("preflight: must be a list")
        else:
            for i, item in enumerate(pf):
                if not isinstance(item, dict):
                    errs.append(f"preflight[{i}]: must be an object")
                    continue
                _unknown(item, PREFLIGHT_KEYS, f"preflight[{i}]", errs)
                if not isinstance(item.get("run"), str) or not item["run"].strip():
                    errs.append(f"preflight[{i}].run: required, a non-empty command string")
                if item.get("in", "worktree") not in ("main", "worktree"):
                    errs.append(f"preflight[{i}].in: `main` or `worktree`")
                if "hint" in item and not isinstance(item["hint"], str):
                    errs.append(f"preflight[{i}].hint: must be a string")
    if "ports" in cfg:
        p = cfg["ports"]
        if not isinstance(p, dict):
            errs.append("ports: must be an object {KEY: base port}")
        else:
            for k, v in p.items():
                if not ENV_KEY_RE.match(k):
                    errs.append(f"ports.{k}: not an env var name")
                if not (_is_int(v) and 1 <= v <= 65535 - (SLOT_COUNT - 1)):
                    errs.append(f"ports.{k}: base must be an integer from 1 to {65535 - (SLOT_COUNT - 1)}")
            bases = sorted(v for v in p.values() if _is_int(v))
            if any(b - a < SLOT_COUNT for a, b in zip(bases, bases[1:])):
                errs.append(f"ports: bases must be at least {SLOT_COUNT} apart (each worktree adds its slot)")
    if "ports_from" in cfg:
        pf = cfg["ports_from"]
        if not isinstance(pf, dict):
            errs.append("ports_from: must be an object with env_file")
        else:
            _unknown(pf, {"env_file", "keys", "main"}, "ports_from", errs)
            if not isinstance(pf.get("env_file"), str) or _bad_relpath(pf["env_file"]):
                errs.append("ports_from.env_file: must be a relative path inside the worktree")
            if "keys" in pf and not (_is_str_list(pf["keys"]) and pf["keys"]
                                     and all(ENV_KEY_RE.fullmatch(k) for k in pf["keys"])):
                errs.append("ports_from.keys: must be a non-empty list of env var names")
            if "main" in pf and not (isinstance(pf["main"], dict) and all(
                    ENV_KEY_RE.fullmatch(k) and _is_int(port) and 0 < port < 65536
                    for k, port in pf["main"].items())):
                errs.append("ports_from.main: must map env var names to port numbers")
    if "env" in cfg:
        e = cfg["env"]
        if not (isinstance(e, dict) and all(ENV_KEY_RE.match(k) and isinstance(v, str) for k, v in e.items())):
            errs.append("env: must be an object of env var names to string values")
    if "env_strip" in cfg and not (_is_str_list(cfg["env_strip"])
                                   and all(ENV_KEY_RE.match(k) for k in cfg["env_strip"])):
        errs.append("env_strip: must be a list of env var names")
    if "max_running" in cfg and not (_is_int(cfg["max_running"]) and cfg["max_running"] >= 1):
        errs.append("max_running: must be an integer of at least 1")
    if "idle_timeout_minutes" in cfg and not (_is_int(cfg["idle_timeout_minutes"])
                                              and cfg["idle_timeout_minutes"] >= 0):
        errs.append("idle_timeout_minutes: must be an integer of at least 0 (0 = off)")
    if "servers" in cfg:
        sv = cfg["servers"]
        if not isinstance(sv, dict):
            errs.append("servers: must be an object of name -> server")
        else:
            for name, s in sv.items():
                _check_server(name, s, errs)
    if errs:
        raise ToolError(f"invalid config ({label}):\n" + "\n".join(f"- {e}" for e in errs))
    return cfg


def _bad_relpath(p: str) -> bool:
    if not p or os.path.isabs(p) or "\x00" in p:
        return True
    return ".." in Path(os.path.normpath(p)).parts or os.path.normpath(p) == "."


def merge_config(team: dict | None, local: dict | None) -> dict | None:
    """Top-level keys of local replace team's; `servers` merge by name."""
    if team is None and local is None:
        return None
    merged = {**(team or {}), **(local or {})}
    servers = {**(team or {}).get("servers", {}), **(local or {}).get("servers", {})}
    if servers:
        merged["servers"] = servers
    return merged


def check_merged(cfg: dict) -> dict:
    errs: list[str] = []
    servers = cfg.get("servers") or {}
    if not servers:
        errs.append("servers: at least one server is required")
    defaults = [n for n, s in servers.items() if s.get("default")]
    if len(defaults) > 1:
        errs.append(f"servers: more than one default ({', '.join(defaults)})")
    if errs:
        raise ToolError("invalid config (merged):\n" + "\n".join(f"- {e}" for e in errs))
    return cfg


def config_hash(cfg: dict) -> str:
    return hashlib.sha256(json.dumps(cfg, sort_keys=True, separators=(",", ":"), ensure_ascii=False)
                          .encode("utf-8")).hexdigest()


def _read_config_file(path: Path, label: str) -> dict | None:
    if not path.is_file():
        return None
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError, UnicodeDecodeError) as e:
        raise ToolError(f"cannot read {path}: {e}") from e
    return check_schema(data, f"{label} {path}")


def load_config(ctx: Ctx) -> dict | None:
    """Read worktree config, with an opt-in fallback from the main checkout."""
    agents = Path(ctx.worktree) / ".agents"
    team = _read_config_file(agents / TEAM_FILE, "team")
    local = _read_config_file(agents / LOCAL_FILE, "local")
    if team is None and local is None and ctx.worktree != ctx.root:
        main_path = Path(ctx.root) / ".agents" / LOCAL_FILE
        main_local = _read_config_file(main_path, "main local")
        if main_local and main_local.get("inherit_worktrees"):
            local = main_local
            team = _read_config_file(main_path.with_name(TEAM_FILE), "main team")
    merged = merge_config(team, local)
    return check_merged(merged) if merged is not None else None


